"""
analyse_results.py
──────────────────
Run this after your 100 bench tests to compute all metrics.

Usage:
    python analyse_results.py

It reads two files:
  1. results.csv          — auto-generated by test_logger.py
  2. ground_truth.csv     — filled in manually (template printed on first run)

Output:
  - Metrics printed to terminal
  - summary_report.csv saved alongside

GROUND TRUTH CSV columns (fill in manually after each test):
    test_id, object_present, true_class, true_side, notes
    e.g.  1, Yes, person, LEFT, "good lighting"
          2, No,  none,   none, "false positive test"
"""

import csv
import os
import statistics
from collections import defaultdict

RESULTS_CSV     = "results.csv"
GROUND_TRUTH_CSV= "ground_truth.csv"
SUMMARY_CSV     = "summary_report.csv"


# ─────────────────────────────────────────────
# HELPERS
# ─────────────────────────────────────────────
def load_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))

def safe_float(val):
    try:
        return float(val)
    except (ValueError, TypeError):
        return None

def pct(num, denom):
    return round(100 * num / denom, 1) if denom else 0.0


# ─────────────────────────────────────────────
# GROUND TRUTH TEMPLATE
# ─────────────────────────────────────────────
def create_gt_template(results):
    """Generate a blank ground_truth.csv for manual filling."""
    with open(GROUND_TRUTH_CSV, "w", newline="") as f:
        writer = csv.DictWriter(
            f, fieldnames=["test_id","object_present","true_class","true_side","notes"]
        )
        writer.writeheader()
        for row in results:
            writer.writerow({
                "test_id":        row["test_id"],
                "object_present": "",   # fill: Yes / No
                "true_class":     "",   # fill: person / car / none
                "true_side":      "",   # fill: LEFT / CENTRE / RIGHT / none
                "notes":          "",
            })
    print(f"[Template] '{GROUND_TRUTH_CSV}' created — fill it in then re-run this script.")


# ─────────────────────────────────────────────
# METRICS
# ─────────────────────────────────────────────
def compute_detection_metrics(results, ground_truth):
    """Precision, Recall, F1 for object detection."""
    gt_map = {row["test_id"]: row for row in ground_truth}

    TP = FP = FN = TN = 0

    for row in results:
        tid      = row["test_id"]
        detected = row["detected_classes"] != "None" and row["detected_classes"] != ""
        gt       = gt_map.get(tid, {})
        present  = str(gt.get("object_present", "")).strip().lower() == "yes"

        if detected and present:   TP += 1
        elif detected and not present: FP += 1
        elif not detected and present: FN += 1
        else:                          TN += 1

    precision = TP / (TP + FP) if (TP + FP) else 0
    recall    = TP / (TP + FN) if (TP + FN) else 0
    f1        = (2 * precision * recall / (precision + recall)
                 if (precision + recall) else 0)
    accuracy  = (TP + TN) / len(results) if results else 0

    return {
        "Total tests":   len(results),
        "TP": TP, "FP": FP, "FN": FN, "TN": TN,
        "Precision %":   round(precision * 100, 1),
        "Recall %":      round(recall    * 100, 1),
        "F1 Score":      round(f1,              3),
        "Accuracy %":    round(accuracy  * 100, 1),
    }


def compute_side_metrics(results, ground_truth):
    """Side classification accuracy (LEFT/CENTRE/RIGHT)."""
    gt_map  = {row["test_id"]: row for row in ground_truth}
    correct = 0
    total   = 0
    confusion = defaultdict(lambda: defaultdict(int))  # confusion[true][pred]

    for row in results:
        tid       = row["test_id"]
        predicted = row["side_classified"].strip()
        gt        = gt_map.get(tid, {})
        true_side = str(gt.get("true_side", "")).strip().upper()

        if true_side in ("LEFT", "CENTRE", "RIGHT") and predicted in ("LEFT", "CENTRE", "RIGHT"):
            total += 1
            confusion[true_side][predicted] += 1
            if predicted == true_side:
                correct += 1

    return {
        "Side tests":          total,
        "Side correct":        correct,
        "Side accuracy %":     pct(correct, total),
        "Confusion matrix":    dict(confusion),
    }


def compute_reaction_times(results):
    """Reaction time stats in ms."""
    times = [safe_float(r["reaction_time_ms"])
             for r in results if safe_float(r["reaction_time_ms"]) is not None]

    if not times:
        return {"Reaction time note": "No reaction time data recorded"}

    return {
        "Reaction time samples": len(times),
        "Min ms":     round(min(times),              1),
        "Max ms":     round(max(times),              1),
        "Mean ms":    round(statistics.mean(times),  1),
        "Median ms":  round(statistics.median(times),1),
        "Stdev ms":   round(statistics.stdev(times), 1) if len(times) > 1 else 0,
    }


def compute_manoeuvre_metrics(results):
    """How often manoeuvres triggered and breakdown by type."""
    total      = len(results)
    triggered  = [r for r in results if r["manoeuvre_triggered"] == "Yes"]
    by_type    = defaultdict(int)
    by_side    = defaultdict(int)

    for r in triggered:
        by_type[r["manoeuvre_type"]] += 1
        by_side[r["manoeuvre_side"]] += 1

    return {
        "Manoeuvres triggered":   len(triggered),
        "Manoeuvre rate %":       pct(len(triggered), total),
        "By type":                dict(by_type),
        "By side":                dict(by_side),
    }


def compute_per_class_metrics(results, ground_truth):
    """Per-class breakdown for person and car."""
    gt_map   = {row["test_id"]: row for row in ground_truth}
    classes  = ["person", "car"]
    stats    = {}

    for cls in classes:
        TP = FP = FN = 0
        for row in results:
            tid       = row["test_id"]
            detected  = cls in row["detected_classes"].lower()
            gt        = gt_map.get(tid, {})
            true_cls  = str(gt.get("true_class", "")).strip().lower()
            present   = true_cls == cls

            if detected and present:       TP += 1
            elif detected and not present: FP += 1
            elif not detected and present: FN += 1

        precision = TP/(TP+FP) if (TP+FP) else 0
        recall    = TP/(TP+FN) if (TP+FN) else 0
        f1        = (2*precision*recall/(precision+recall)
                     if (precision+recall) else 0)
        stats[cls] = {
            "TP": TP, "FP": FP, "FN": FN,
            "Precision %": round(precision*100,1),
            "Recall %":    round(recall*100,   1),
            "F1":          round(f1,           3),
        }
    return stats


# ─────────────────────────────────────────────
# PRINT + SAVE
# ─────────────────────────────────────────────
def print_section(title, data):
    print(f"\n{'─'*50}")
    print(f"  {title}")
    print(f"{'─'*50}")
    if isinstance(data, dict):
        for k, v in data.items():
            print(f"  {k:<30} {v}")
    else:
        print(data)

def save_summary(all_metrics):
    rows = []
    for section, data in all_metrics.items():
        if isinstance(data, dict):
            for k, v in data.items():
                rows.append({"section": section, "metric": k, "value": str(v)})
    with open(SUMMARY_CSV, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["section","metric","value"])
        writer.writeheader()
        writer.writerows(rows)
    print(f"\n[Saved] Summary written to '{SUMMARY_CSV}'")


# ─────────────────────────────────────────────
# MAIN
# ─────────────────────────────────────────────
def main():
    print("\n══════════════════════════════════════════════════")
    print("   AUTONOMOUS NAVIGATION — BENCH TEST ANALYSIS")
    print("══════════════════════════════════════════════════")

    # Load results
    if not os.path.exists(RESULTS_CSV):
        print(f"[Error] '{RESULTS_CSV}' not found. Run the dashboard tests first.")
        return
    results = load_csv(RESULTS_CSV)
    print(f"\n[Loaded] {len(results)} rows from '{RESULTS_CSV}'")

    # Load or create ground truth
    if not os.path.exists(GROUND_TRUTH_CSV):
        print(f"[Info] '{GROUND_TRUTH_CSV}' not found — generating template...")
        create_gt_template(results)
        return
    ground_truth = load_csv(GROUND_TRUTH_CSV)

    # Check if ground truth is filled in
    unfilled = sum(1 for r in ground_truth if not r["object_present"].strip())
    if unfilled > 0:
        print(f"[Warning] {unfilled} rows in ground_truth.csv are still blank. "
              f"Fill them in for full metrics.")

    # Compute all metrics
    det_metrics  = compute_detection_metrics(results, ground_truth)
    side_metrics = compute_side_metrics(results, ground_truth)
    rxn_metrics  = compute_reaction_times(results)
    man_metrics  = compute_manoeuvre_metrics(results)
    cls_metrics  = compute_per_class_metrics(results, ground_truth)

    # Print
    print_section("DETECTION ACCURACY",  det_metrics)
    print_section("SIDE CLASSIFICATION", side_metrics)
    print_section("REACTION TIME",       rxn_metrics)
    print_section("MANOEUVRE SUMMARY",   man_metrics)

    print(f"\n{'─'*50}")
    print("  PER-CLASS BREAKDOWN")
    print(f"{'─'*50}")
    for cls, stats in cls_metrics.items():
        print(f"\n  [{cls.upper()}]")
        for k, v in stats.items():
            print(f"    {k:<28} {v}")

    # Save summary
    all_metrics = {
        "Detection Accuracy":  det_metrics,
        "Side Classification": side_metrics,
        "Reaction Time":       rxn_metrics,
        "Manoeuvre Summary":   man_metrics,
        **{f"Class: {cls}": stats for cls, stats in cls_metrics.items()},
    }
    save_summary(all_metrics)


if __name__ == "__main__":
    main()